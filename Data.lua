-- ns.grimoires: one entry per family, sorted by level, then family order.
-- ns.chains[family][ability]: entries of one ability, lowest rank first.
-- ns.byItem[itemId]: the entries one grimoire teaches (two for Sayaad grimoires).
ns.grimoires = {}
ns.chains = {}
ns.byItem = {}

local familyOrder = {}
for i, family in ipairs(ns.FAMILIES) do
    familyOrder[family] = i
    ns.chains[family] = {}
end

for _, row in ipairs(RAW) do
    local level, itemId, spellId, cost, family, ability = unpack(row)
    local families = family == "Sayaad" and { "Succubus", "Incubus" } or { family }
    for _, f in ipairs(families) do
        local entry = {
            key = f .. ":" .. itemId,
            level = level,
            itemId = itemId,
            spellId = spellId,
            cost = cost,
            family = f,
            ability = ability,
        }
        table.insert(ns.grimoires, entry)
        local chain = ns.chains[f][ability] or {}
        ns.chains[f][ability] = chain
        table.insert(chain, entry)
        ns.byItem[itemId] = ns.byItem[itemId] or {}
        table.insert(ns.byItem[itemId], entry)
    end
end

table.sort(ns.grimoires, function(a, b)
    if a.level ~= b.level then return a.level < b.level end
    if a.family ~= b.family then return familyOrder[a.family] < familyOrder[b.family] end
    return a.itemId < b.itemId
end)

for _, abilities in pairs(ns.chains) do
    for _, chain in pairs(abilities) do
        table.sort(chain, function(a, b) return a.level < b.level end)
    end
end
